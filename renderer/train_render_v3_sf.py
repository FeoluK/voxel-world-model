"""render_v3 SELF-FORCING (DAgger / scheduled-sampling) fine-tune.

This is train_render_v3.py with ONE conceptual change to the training loop:

  Teacher-forced base trains the prev-frame branch on the CLEAN GT previous
  frame (prev[:,:,1:] = x0[:,:,:-1]).  At inference (validate_v3 ar=True) the
  prev frame is the model's OWN noisy prediction -> train/test mismatch ->
  autoregressive drift.

  Self-forcing fixes this with DAgger: with probability sf_prob (ramped from 0
  to sf_prob_hi over phase_steps) a step CONDITIONS on the model's OWN previously
  predicted frames (generated by a CHEAP, DETACHED autoregressive ODE rollout,
  exactly the validate_v3 ar pattern) instead of the GT-shifted prev, while the
  graded flow/tc/pc losses STILL supervise toward the GROUND-TRUTH x0.  So the
  model learns to recover from its own conditioning errors.

Everything else (CondEncoderV3, FlowVNetV3, make_cond_v3, rectified-flow
convention, tc + pc losses, grad-ckpt, DDP, bf16 autocast, checkpoint meta) is
IDENTICAL to the base.  Checkpoints go to a SEPARATE dir / names (v3sf_*) so the
base checkpoints are never touched, and carry the SAME meta keys so validate_v3
can load them.

--resume (REQUIRED) warm-starts from a v3 BASE ckpt.  If a v3sf_latest.pt already
exists in --ckpt_dir, that SF checkpoint is resumed instead (self-resume).
"""
